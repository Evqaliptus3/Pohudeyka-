export function findFood(name) {
  return FOODS.find((f) => f.name === name);
}

export function mealItems(meal) {
  return meal.items.map(([name, g]) => {
    const f = findFood(name);
    if (!f) throw new Error('Нет продукта: ' + name);
    return { ...portion(f, g), base: { kcal: f.kcal, p: f.p, f: f.f, c: f.c }, unit: f.unit, unitG: f.unitG };
  });
}

export function mealTotals(meal) {
  return mealItems(meal).reduce(
    (t, i) => ({ kcal: t.kcal + i.kcal, p: t.p + i.p, f: t.f + i.f, c: t.c + i.c }),
    { kcal: 0, p: 0, f: 0, c: 0 },
  );
}

// Перевод продукта (на 100 г) в порцию нужного веса
export function portion(food, grams) {
  const k = grams / 100;
  return {
    name: food.name,
    grams,
    kcal: Math.round(food.kcal * k),
    p: Math.round(food.p * k * 10) / 10,
    f: Math.round(food.f * k * 10) / 10,
    c: Math.round(food.c * k * 10) / 10,
  };
}

export function searchFoods(query, custom = []) {
  const q = query.trim().toLowerCase();
  const all = [...custom, ...FOODS];
  if (!q) return all;
  const words = q.split(/\s+/);
  return all
    .filter((f) => words.every((w) => f.name.toLowerCase().includes(w)))
    .sort((a, b) => a.name.toLowerCase().indexOf(words[0]) - b.name.toLowerCase().indexOf(words[0]));
}

// Поиск по базе Open Food Facts (нужен интернет)
export async function searchOnline(query) {
  const url =
    'https://world.openfoodfacts.org/cgi/search.pl?search_simple=1&action=process&json=1&page_size=20&fields=product_name,brands,nutriments&search_terms=' +
    encodeURIComponent(query);
  const res = await fetch(url);
  if (!res.ok) throw new Error('Ошибка сети');
  const data = await res.json();
  return (data.products || [])
    .filter((p) => p.product_name && p.nutriments && p.nutriments['energy-kcal_100g'] != null)
    .map((p, i) => ({
      id: 'off' + i,
      name: p.product_name + (p.brands ? ` (${p.brands.split(',')[0]})` : ''),
      kcal: Math.round(p.nutriments['energy-kcal_100g']),
      p: Math.round((p.nutriments.proteins_100g || 0) * 10) / 10,
      f: Math.round((p.nutriments.fat_100g || 0) * 10) / 10,
      c: Math.round((p.nutriments.carbohydrates_100g || 0) * 10) / 10,
      online: true,
    }));
}
